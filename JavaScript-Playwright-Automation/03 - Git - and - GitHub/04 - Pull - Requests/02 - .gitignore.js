// Q1. Purpose of .gitignore?
// It tells Git which files or folders to ignore — meaning Git won't track changes to them or allow them to be accidentally committed. This keeps unnecessary, generated, or sensitive files out of the repository.

// Q2. Why add node_modules/ to .gitignore?
// Because node_modules/ contains all installed npm packages, which can be huge and are easily regenerated by running npm install using package.json/package-lock.json. There's no need to commit it — it would bloat the repository unnecessarily and isn't something developers need to track changes on.

// Q3. Why might .env be in .gitignore?
// Because .env files typically store sensitive information like API keys, passwords, or tokens. Committing it to Git would expose those secrets to anyone with access to the repository, which is a security risk — especially in public repos.

// Q4. Does adding an already-tracked file to .gitignore remove it from tracking?
// No. .gitignore only prevents new, untracked files from being added to Git. If a file is already being tracked, Git continues tracking it even after adding it to .gitignore. To stop tracking it, you'd need to explicitly remove it from Git's tracking using a command like git rm --cached <file>, and then commit that change.

