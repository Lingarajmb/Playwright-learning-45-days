// 🧠 What is an Object?
// An object stores related information using key-value pairs.

// Example:
// const user = {
//     name: "Lingaraj",
//     age: 28,
//     role: "QA Engineer"
// };
// console.log(user);

// Here:
// name  → "Lingaraj"
// age   → 28
// role  → "QA Engineer"
// name, age, and role are called properties/keys.

// The values are:
// "Lingaraj"
// 28
// "QA Engineer"

// 🔹 Accessing Object Properties
// We can use dot notation:
// console.log(user.name);

// Output:
// Lingaraj

// Or bracket notation:
// console.log(user["age"]);

// Output:
// 28

// 🧠 Easy memory
// user.name
// ➡️ Dot notation
// user["name"]

// ➡️ Bracket notation
// Both access the same property.

