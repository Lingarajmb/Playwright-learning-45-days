// Assignment Operators

let va = 10;
va += 5; // va = va + 5
console.log(va);

let vb = 10;
vb -= 3; // vb = vb - 3
console.log(vb);

let vc = 10;
vc *= 2; // vc = vc * 2
console.log(vc);

let vd = 10;
vd /= 4; // vd = vd / 4
console.log(vd);

let ve = 10;
ve %= 3; // ve = ve % 3
console.log(ve);

let vf = 10;
vf **= 2; // vf = vf ** 2
console.log(vf);