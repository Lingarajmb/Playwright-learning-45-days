// >     // Greater than
// <     // Less than
// >=    // Greater than or equal to
// <=    // Less than or equal to

let a = 10;
let b = 20;

console.log(a > b);   // false
console.log(a < b);   // true
console.log(a >= b);  // false
console.log(a <= b);  // true


// Easy way to remember

// Comparison → Equal or not equal
// ==  ===  !=  !==

// Relational → Greater or smaller
// >  <  >=  <=