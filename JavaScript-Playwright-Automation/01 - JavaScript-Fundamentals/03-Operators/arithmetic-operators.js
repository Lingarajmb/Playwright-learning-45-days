
//Arithmetic operators

//addition
let x = 10;
let y = 12;
let z = x + y; //addition
console.log("Addition of " + x + " and " + y + " is " + z); //o/p : 22

//Subtraction
let a = 20;
let b = 8;
let c = a - b; // Subtraction
console.log(c); //o/p: 12

// Multiplication
let e = 30;
let f = 2;
let g = e * f; // Multiplication
console.log(g); //o/p : 60

// Division
let i = 10;
let j = 2;
let k = i / j; // Division
console.log(k); // o/p : 5

// Modulus
let l = 20;
let m = 2;
let o = l % m; // Modulus
console.log(o); // o/p : 0


// Increment and Decrement Operators
// Increment
let p = 10;
p++; // Increment 
console.log(p); // o/p : 11

//Decrement
let q = 20;
q--; //Decrement 
console.log(q); // o/p : 19

//PostIncrement
let postIncriment = 90;
postIncriment++;
console.log(postIncriment); //o/p : (90 + 1) = 91

//PreIncriment
let preIncriment = 80;
++preIncriment;
console.log(preIncriment); // o/p : (1 + 80) = 81