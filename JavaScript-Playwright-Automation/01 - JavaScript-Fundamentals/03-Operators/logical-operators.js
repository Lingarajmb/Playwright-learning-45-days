// Logical Operators

// AND
let m1 = true;
let n1 = false;
console.log(m1 && n1); // false

// OR
let o1 = true;
let p1 = false;
console.log(o1 || p1); // true

// NOT
let q1 = true;
console.log(!q1); // false

// Ternary Operator
let age = 18;
let canVote = (age >= 18) ? 'Yes' : 'No';
console.log(canVote); // Yes

